                } else if name.contains("bar") || name.contains("pub") || name.contains("brewery") {
                    self.selectedCategory = .bar
                } else if name.contains("hotel") || name.contains("inn") || name.contains("motel") {
                    self.selectedCategory = .hotel
                } else if name.contains("store") || name.contains("shop") || name.contains("market") {
                    self.selectedCategory = .retail
                } else {
                    self.selectedCategory = .other
                }
            }
            
            // Update category button text
            if let subcategory = self.selectedSubcategory {
                self.categoryButton.setTitle("\(self.selectedCategory.displayName) - \(subcategory)", for: .normal)
            } else {
                self.categoryButton.setTitle(self.selectedCategory.displayName, for: .normal)
            }
            
            // Update selected location - use coordinate directly as it's always available
            self.selectedLocation = mapItem.placemark.coordinate
            
            // Force UI refresh
            self.view.setNeedsLayout()
            self.view.layoutIfNeeded()
            
            // Debug: Log what was filled
            Logger.debug("📝 Form filled with:")
            Logger.debug("  - Name: \(self.nameTextField.text ?? "empty")")
            Logger.debug("  - Address: \(self.addressTextView.text ?? "empty")")
            Logger.debug("  - Description: \(self.descriptionTextView.text ?? "empty")")
            Logger.debug("  - Category: \(self.selectedCategory.displayName)")
            Logger.debug("  - Form enabled: \(self.formContainer.isUserInteractionEnabled)")
            
            // Attach googlePlaceId + photos (only for businesses, not
            // residential). Checks our own database first — Google is only
            // queried for venues nobody has saved yet.
            if !isResidentialAddress, let placeName = mapItem.name, !placeName.isEmpty {
                self.fetchPlaceAssets(
                    name: placeName,
                    coordinate: mapItem.placemark.coordinate,
                    address: address
                )
            }
            
            // Update map to show the selected place
            self.showBothUserAndPlace(placeCoordinate: mapItem.placemark.coordinate)
            
            // Pin carries the picked venue's name — the generic green
            // "Selected Location" hid that the fallback sometimes grabs a
            // different business than the label the user aimed at
            self.addSelectedLocationPin(at: mapItem.placemark.coordinate,
                                        title: mapItem.name ?? "Selected Location",
                                        subtitle: mapItem.name == nil ? "Place will be added here" : "Venue selected",
                                        category: mapItem.name == nil ? nil : self.selectedCategory)
            
            // Scroll to show form after a delay
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) {
                self.scrollToFormTop()
                // Reset the flag after form is filled and scrolled
                self.isFillingForm = false
            }

            // A picked ADDRESS entity (no POI category, name = the street
            // address) usually means the user wanted the business AT that
            // address — "300 East Blvd" saved when they meant the restaurant
            // "300 East". Look for a matching business and offer it by name.
            self.offerBusinessSuggestionIfBareAddress(for: mapItem)
        }
    }

    // MARK: - Bare-address → business suggestion

    /// A street-address entity rather than a business (see BareAddressHeuristic).
    private static func isBareAddressItem(_ mapItem: MKMapItem) -> Bool {
        let placemark = mapItem.placemark
        return BareAddressHeuristic.isBareAddress(
            name: mapItem.name,
            hasPointOfInterestCategory: mapItem.pointOfInterestCategory != nil,
            subThoroughfare: placemark.subThoroughfare,
            thoroughfare: placemark.thoroughfare
        )
    }

    private static func namesRelated(business: String, address: String) -> Bool {
        BareAddressHeuristic.namesRelated(business: business, address: address)
    }

    private func offerBusinessSuggestionIfBareAddress(for addressItem: MKMapItem) {
        guard Self.isBareAddressItem(addressItem), let addressName = addressItem.name else { return }

        let coordinate = addressItem.placemark.coordinate
        let request = MKLocalPointsOfInterestRequest(center: coordinate, radius: 120)
        MKLocalSearch(request: request).start { [weak self] response, _ in
            guard let self = self, let items = response?.mapItems else { return }

            let origin = CLLocation(latitude: coordinate.latitude, longitude: coordinate.longitude)
            let candidates = items
                .filter { item in
                    guard item.pointOfInterestCategory != nil,
                          let name = item.name, !name.isEmpty else { return false }
                    let distance = origin.distance(from: CLLocation(
                        latitude: item.placemark.coordinate.latitude,
                        longitude: item.placemark.coordinate.longitude))
                    return distance <= 120 && Self.namesRelated(business: name, address: addressName)
                }
                .sorted { a, b in
                    origin.distance(from: CLLocation(latitude: a.placemark.coordinate.latitude,
                                                     longitude: a.placemark.coordinate.longitude)) <
                    origin.distance(from: CLLocation(latitude: b.placemark.coordinate.latitude,
                                                     longitude: b.placemark.coordinate.longitude))
                }
                .prefix(3)

            guard !candidates.isEmpty else { return }

            DispatchQueue.main.async {
                // Don't fight a modal (photo picker, category sheet…)
                guard self.presentedViewController == nil else { return }
                AlertPresenter.showActionSheet(
                    title: "Did you mean this place?",
                    message: "\"\(addressName)\" is an address — there's a business here:",
                    actions: candidates.map { item in
                        (title: item.name ?? "", style: .default, handler: { [weak self] in
                            // Refill the whole form from the business POI —
                            // name, category, photos, description all follow
                            self?.fillFormWithMapItem(item)
                        })
                    },
                    from: self
                )
            }
        }
    }

