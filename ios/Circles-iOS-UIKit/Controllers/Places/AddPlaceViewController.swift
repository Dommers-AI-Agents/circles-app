        if !hasAnnotation {
            let annotation = PlaceSearchAnnotation()
            annotation.coordinate = coordinate
            annotation.title = "Selected Location"
            annotation.isTemporary = true
            mapView.addAnnotation(annotation)
        }
    }
    
