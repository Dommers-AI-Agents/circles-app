        tapGesture.cancelsTouchesInView = false
        tapGesture.delegate = self
        view.addGestureRecognizer(tapGesture)
        
        // Don't set initial region - wait for user location
        
        // Load user circles - use injected circles when available (no network call)
        if let injected = injectedCircles, !injected.isEmpty {
            applyUserCircles(injected)
        } else {
            loadUserCircles()
        }
    }
    
    override func viewDidAppear(_ animated: Bool) {
        super.viewDidAppear(animated)
        
        // Force map to render properly
        mapView.setNeedsDisplay()
        
        // One-time hint bubble for new users explaining how to add a place
        // (the old cross-screen tutorial step was removed 2026-08-19 — the
        // tour now lives on the home page)
        if OnboardingManager.shared.shouldShowAddPlaceMapHint() {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { [weak self] in
                self?.showAddPlaceMapHintBubble()
            }
        }
        
        // Check current authorization status
        checkLocationAuthorizationOnAppear()
    }

    /// One-time bubble pointing at the search bar (hovering over the map)
    /// telling new users how to add a place. Marked as shown immediately so
    /// it only ever appears once.
    func showAddPlaceMapHintBubble() {
        guard OnboardingManager.shared.shouldShowAddPlaceMapHint() else { return }

        // The "shown once" flag is device-local, so a fresh install or
        // re-login re-arms it for long-time users. If this account already
        // has places anywhere, they don't need a how-to — retire the hint
        // without showing it. Circles still loading → decide on a later open
        // instead of guessing.
        guard !userCircles.isEmpty else { return }
        let hasExistingPlaces = userCircles.contains { ($0.placesCount ?? $0.places?.count ?? 0) > 0 }
        if hasExistingPlaces {
            OnboardingManager.shared.markAddPlaceMapHintShown()
            return
        }

        // The hint explains how to pick a place — skip it when one is already
        // in the form (prefilled from a POI, check-in, or another screen)
        guard !isFillingForm, (nameTextField.text ?? "").isEmpty else { return }

        OnboardingManager.shared.markAddPlaceMapHintShown()

        let bubble = BubbleView()
        bubble.configureHint(
            title: "Add a Place",
            description: "Tap a place on the map or use the search bar",
            arrowDirection: .top
        )
        bubble.onNext = { [weak bubble] in
            bubble?.dismiss {
                bubble?.removeFromSuperview()
            }
        }

        view.addSubview(bubble)
        bubble.pointTo(searchBar, in: view)
        bubble.show()
    }

