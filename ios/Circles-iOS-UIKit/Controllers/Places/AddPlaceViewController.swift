    @objc func handleMapTap(_ gesture: UITapGestureRecognizer) {
        let location = gesture.location(in: mapView)
        let coordinate = mapView.convert(location, toCoordinateFrom: mapView)

        // Delay the manual-location handling so a POI/annotation selection
        // triggered by this same tap can cancel it. Without this, the manual
        // path's reverse geocode wipes the form the POI selection just filled.
        pendingManualMapTap?.cancel()
        let workItem = DispatchWorkItem { [weak self] in
            self?.handleMapTapAtCoordinate(coordinate)
        }
        pendingManualMapTap = workItem
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.35, execute: workItem)
    }
    
    func handleMapTapAtCoordinate(_ coordinate: CLLocationCoordinate2D) {
        // Tapping the map should select the place at that spot, not drop a bare
        // pin - find the nearest POI around the tap and treat it as a selection.
        // Only when nothing is nearby does it fall back to a manual location pin.
        let request = MKLocalPointsOfInterestRequest(center: coordinate, radius: 100)
        let search = MKLocalSearch(request: request)
        search.start { [weak self] response, _ in
            guard let self = self else { return }

            let tapLocation = CLLocation(latitude: coordinate.latitude, longitude: coordinate.longitude)
            let nearest = response?.mapItems.min { a, b in
                let distanceA = tapLocation.distance(from: CLLocation(latitude: a.placemark.coordinate.latitude,
                                                                      longitude: a.placemark.coordinate.longitude))
                let distanceB = tapLocation.distance(from: CLLocation(latitude: b.placemark.coordinate.latitude,
                                                                      longitude: b.placemark.coordinate.longitude))
                return distanceA < distanceB
            }

            DispatchQueue.main.async {
                if let mapItem = nearest {
                    Logger.debug("📍 Map tap selected nearest place: \(mapItem.name ?? "Unknown")")
                    self.enableManualEntry()
                    self.fillFormWithMapItem(mapItem)
                } else {
                    Logger.debug("📍 No place found near tap - using manual location")
                    self.handleManualLocationTap(at: coordinate)
                }
            }
        }
    }

    /// Fallback when no POI exists near the tapped point: drop a pin and
    /// reverse geocode the address for manual entry.
    func handleManualLocationTap(at coordinate: CLLocationCoordinate2D) {
        // Remove any existing "Selected Location" annotations
        let selectedAnnotations = mapView.annotations.filter { ($0 as? PlaceSearchAnnotation)?.title == "Selected Location" }
        mapView.removeAnnotations(selectedAnnotations)

        // Add new annotation
        let annotation = PlaceSearchAnnotation()
        annotation.coordinate = coordinate
        annotation.title = "Selected Location"
        annotation.subtitle = "Tap here to add this place"
        annotation.isTemporary = true

        mapView.addAnnotation(annotation)
        annotations.append(annotation)

        // Reverse geocode to get address
        let location = CLLocation(latitude: coordinate.latitude, longitude: coordinate.longitude)
        let geocoder = CLGeocoder()
        
        geocoder.reverseGeocodeLocation(location) { [weak self] placemarks, error in
            guard let self = self else { return }
            guard let placemark = placemarks?.first else { return }
            
            DispatchQueue.main.async {
                // Enable manual entry
                self.enableManualEntry()

                // Clear any Google Place details since this is manual
                self.selectedGooglePlaceDetails = nil

                // NEVER bulldoze what the user already typed. This used to
                // clear the whole form and overwrite the address with the
                // pin's reverse-geocode — someone who typed "3212 Shafto Rd"
                // then tapped the map watched their entry become their
                // current location's address. Geocode fills EMPTY fields only.
                let address = [
                    placemark.subThoroughfare,
                    placemark.thoroughfare,
                    placemark.locality,
                    placemark.administrativeArea,
                    placemark.postalCode,
                    placemark.country
                ].compactMap { $0 }.joined(separator: ", ")

                if (self.addressTextView.text ?? "").isEmpty {
                    self.addressTextView.text = address
                }
                self.selectedLocation = coordinate
                
                // Add a pin to show the selected location
                self.addSelectedLocationPin(at: coordinate)
                
                // Search for nearby places at this location
                self.searchNearbyPlaces(at: coordinate)
            }
        }
    }
    
    func searchNearbyPlaces(at coordinate: CLLocationCoordinate2D) {
        Logger.debug("🔍 Searching for nearby places at \(coordinate.latitude), \(coordinate.longitude)")
        
        // Use Google Places to search for nearby businesses
        GooglePlacesService.shared.searchPlacesByCategory(
            category: "",  // Empty query to get all nearby places
            center: coordinate,
            radiusInMeters: 50  // Search within 50 meters
        ) { [weak self] result in
            switch result {
            case .success(let predictions):
                if let nearestPlace = predictions.first {
                    Logger.debug("✅ Found nearby place: \(nearestPlace.attributedPrimaryText.string)")
                    
                    // Fetch details for the nearest place
                    GooglePlacesService.shared.fetchPlaceDetails(placeID: nearestPlace.placeID) { detailsResult in
                        switch detailsResult {
                        case .success(let place):
                            DispatchQueue.main.async {
                                // If we found a place, update the form with its details
                                let googleDetails = GooglePlaceDetails(from: place)
                                self?.selectedGooglePlaceDetails = googleDetails
                                
                                // Update the name field with the found place
