    /// Attach a googlePlaceId and photos to the place being added. Our own
    /// database is checked first: if another user already saved this venue,
    /// the canonical record supplies both and Google Places is never queried.
    /// Apple offers no editorial text, so the form initially shows a
    /// synthesized "Category in City" line. When Google details arrive later
    /// with a real editorial summary, swap it in — keeping the Phone/Website
    /// lines and never touching a description the user has edited.
    func upgradeDescriptionWithEditorialSummary(_ summary: String?) {
        guard let summary = summary?.trimmingCharacters(in: .whitespacesAndNewlines),
              !summary.isEmpty,
              let current = descriptionTextView.text,
              current == (autoGeneratedDescription ?? "") else { return }
        let contactLines = current.components(separatedBy: "\n")
            .filter { $0.hasPrefix("Phone:") || $0.hasPrefix("Website:") }
            .filter { !summary.contains($0) } // canonical text may already include them
        let upgraded = ([summary] + contactLines).joined(separator: "\n")
        descriptionTextView.text = upgraded
        autoGeneratedDescription = upgraded
    }

